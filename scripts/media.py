#!/usr/bin/env python3
"""Index Nexus documentation media and review release impact (stdlib only)."""
import argparse
import datetime
import fnmatch
import hashlib
import json
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
CATALOG = Path('media/catalog.json')
INDEX = Path('media/INDEX.md')
EXTENSIONS = r'png|jpe?g|gif|webp|svg|mp4|webm|mov|avif'
SCOPES = ['README.md', 'guide', 'docs', 'src', '.github', 'skill', 'media/WORKFLOW.md']


def git(root, *args):
    return subprocess.check_output(['git', '-C', str(root), *args], text=True).strip()


def load(root):
    data = json.loads((root / CATALOG).read_text())
    if data.get('schemaVersion') != 1:
        raise ValueError('Unsupported catalog schemaVersion')
    ids = [a['id'] for a in data['assets']]
    if len(set(ids)) != len(ids):
        raise ValueError('Duplicate asset IDs')
    locations = [a.get('path') or a.get('url') for a in data['assets'] if a.get('path') or a.get('url')]
    if len(set(locations)) != len(locations):
        raise ValueError('Duplicate asset locations')
    return data


def local_path(root, relative):
    p = (root / relative).resolve()
    if not p.is_relative_to(root.resolve()):
        raise ValueError(f'Path leaves repository: {relative}')
    return p


def references(root):
    """Scan tracked and unignored source/docs, including unregistered assets."""
    files = git(root, 'ls-files', '--cached', '--others', '--exclude-standard', '--', *SCOPES).splitlines()
    refs = {}
    tracked_urls = {a['url'] for a in load(root)['assets'] if a.get('url')}
    for name in sorted(set(files)):
        p = root / name
        if not p.is_file() or p.suffix not in {'.md', '.html', '.css', '.ts', '.tsx', '.js', '.json', '.yml'}:
            continue
        for line_no, line in enumerate(p.read_text(errors='replace').splitlines(), 1):
            values = re.findall(r'!\[[^\]]*\]\(<?([^\s)]+)>?', line)
            for tag in re.findall(r'<(?:img|video|source)\b[^>]*>', line, re.I):
                values += re.findall(r'''(?:src|poster)=["']([^"']+)["']''', tag)
            values += re.findall(r'''["'(]([^\s"'()<>]+\.(?:''' + EXTENSIONS + r''')(?:\?[^\s"'()<>]*)?)["')]''', line, re.I)
            values += [url for url in tracked_urls if url in line]
            for value in set(values):
                if value.startswith(('data:', '#', '${')):
                    continue
                if value.startswith(('https://', 'http://')):
                    key = value
                else:
                    target = (p.parent / unquote(urlsplit(value).path)).resolve()
                    if not target.is_relative_to(root.resolve()):
                        continue
                    key = target.relative_to(root.resolve()).as_posix()
                refs.setdefault(key, []).append(f'{name}:{line_no}')
    return {k: sorted(set(v)) for k, v in refs.items()}


def media_info(path):
    raw = path.read_bytes()
    if raw.startswith(b'version https://git-lfs.github.com/spec/'):
        raise ValueError(f'{path.name} is an LFS pointer, fetch original bytes first')
    if raw.startswith(b'\x89PNG\r\n\x1a\n'):
        kind = 'png'
        width, height = struct.unpack('>II', raw[16:24])
    elif raw.startswith((b'GIF87a', b'GIF89a')):
        kind = 'gif'
        width, height = struct.unpack('<HH', raw[6:10])
    elif len(raw) > 12 and raw[4:8] == b'ftyp':
        kind, width, height = 'mp4', None, None
    elif raw.startswith(b'\x1aE\xdf\xa3'):
        kind, width, height = 'webm', None, None
    else:
        raise ValueError('Replacement must contain PNG, GIF, MP4 or WebM bytes')
    if path.suffix.lower() != '.' + kind:
        raise ValueError(f'Extension does not match {kind} bytes')
    return {'bytes': len(raw), 'sha256': hashlib.sha256(raw).hexdigest(),
            'width': width, 'height': height}


def tree(root, head):
    return [row.split('\t', 1) for row in git(root, 'ls-tree', '-r', head).splitlines()]


def matches(path, patterns):
    return any(fnmatch.fnmatchcase(path, pattern) for pattern in patterns)


def fingerprint(entries, patterns):
    rows = [f'{path}\t{meta}' for meta, path in entries if matches(path, patterns)]
    return hashlib.sha256('\n'.join(sorted(rows)).encode()).hexdigest()


def index_text(data, refs):
    lines = ['# Nexus media index', '',
             'Generated by `python3 scripts/media.py index`. Do not edit placement lists by hand.', '',
             '[Visual guide](../guide/visual-tour.md) · [Capture and replacement workflow](WORKFLOW.md) · [Catalog](catalog.json)', '',
             'Scans README, guide, docs, src, .github, skill and media/WORKFLOW.md tracked by Git or not ignored. '
             'Includes image embeds, HTML src/poster, and literal media links. Computed runtime paths, '
             'external course pages and their live placements require manual review; private vaults are not scanned.', '']
    known = set()
    for asset in data['assets']:
        location = asset.get('path') or asset.get('url')
        if location:
            known.add(location)
        lines += [f"## {asset['id']} — {asset['title']}", '',
                  f"Status: **{asset['status']}**. {asset.get('description', '')}", '']
        if location:
            target = location if location.startswith('http') else '../' + location
            lines += [f'[Open asset]({target})', '']
        if asset.get('capture'):
            c = asset['capture']
            lines += [f"Capture: Nexus {c['pluginVersion']}, {c['platform']}, {c['date']}.", '']
        if asset.get('source'):
            lines += [f"Source: {asset['source']}", '']
        placements = refs.get(location, []) if location else []
        lines += ['Placements:', ''] + [f'- `{p}`' for p in placements] if placements else ['Placements: none in scanned repository files.']
        lines += ['', 'Refresh recipe: ' + asset.get('recipe', 'Review source and recapture the same outcome.'), '',
                  'Watch: ' + ', '.join(f'`{p}`' for p in asset.get('watch', [])), '']
    lines += ['## Other discovered media references', '',
              'These are indexed even without a catalog entry. Register product screenshots and demos; '
              'badges and mockup/example references can remain here.', '']
    for location, places in sorted(refs.items()):
        if location not in known:
            lines += [f'- `{location}` — ' + ', '.join(f'`{p}`' for p in places)]
    return '\n'.join(lines).rstrip() + '\n'


def validate(root, data, refs):
    errors = []
    for a in data['assets']:
        if a['status'] not in {'published', 'planned', 'source-only', 'retired'}:
            errors.append(f"{a['id']}: invalid status")
        if not a.get('watch') or not a.get('recipe'):
            errors.append(f"{a['id']}: watch paths and refresh recipe required")
        if a.get('path'):
            p = local_path(root, a['path'])
            if not p.is_file():
                errors.append(f"{a['id']}: missing {a['path']}")
            else:
                for field, value in media_info(p).items():
                    if a.get(field) != value:
                        errors.append(f"{a['id']}: {field} mismatch")
        if a['status'] == 'published' and not (a.get('path') or a.get('url')):
            errors.append(f"{a['id']}: published asset has no location")
    registered = {a.get('path') for a in data['assets']}
    for p in (root / 'media').rglob('*'):
        if p.is_file() and re.search(r'\.(?:' + EXTENSIONS + ')$', p.name, re.I):
            rel = p.relative_to(root).as_posix()
            if rel not in registered:
                errors.append(f'Unregistered local media: {rel}')
    for location in refs:
        if not location.startswith('http') and not local_path(root, location).is_file():
            # Example strings in source/mockups need manual review; published docs cannot have broken embeds.
            if any(p.startswith(('README.md:', 'guide/')) for p in refs[location]):
                errors.append(f'Missing documentation media: {location}')
    expected = index_text(data, refs)
    if not (root / INDEX).exists() or (root / INDEX).read_text() != expected:
        errors.append('Media index stale: run python3 scripts/media.py index')
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, default=ROOT)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('index', help='Regenerate complete asset/placement index')
    sub.add_parser('check', help='Check bytes, metadata, registration and index drift')
    review = sub.add_parser('review', help='List assets affected by a committed release diff; pending reviews exit 1')
    review.add_argument('--base', required=True)
    review.add_argument('--head', default='HEAD')
    approve = sub.add_parser('approve', help='Record human/agent visual review against committed watch paths')
    approve.add_argument('id')
    approve.add_argument('--decision', choices=['keep', 'replaced'], required=True)
    approve.add_argument('--note', required=True)
    approve.add_argument('--head', default='HEAD')
    replace = sub.add_parser('replace', help='Replace a local asset at its stable path; update metadata and index')
    replace.add_argument('id')
    replace.add_argument('--file', type=Path, required=True)
    replace.add_argument('--plugin-version', required=True)
    replace.add_argument('--platform', required=True)
    replace.add_argument('--date', default=datetime.date.today().isoformat())
    args = parser.parse_args()
    root = args.repo.resolve()
    data = load(root)
    if args.command == 'check':
        errors = validate(root, data, references(root))
        print('\n'.join(errors) if errors else 'Media catalog and placement index are current.')
        return int(bool(errors))
    if args.command == 'review':
        changes = git(root, 'diff', '--name-only', args.base, args.head, '--').splitlines()
        entries = tree(root, args.head)
        refs = references(root)
        pending = 0
        for a in data['assets']:
            if a['status'] in {'planned', 'retired', 'source-only'}:
                continue
            hits = [p for p in changes if matches(p, a['watch'])]
            if not hits:
                continue
            reviewed = a.get('review', {}).get('fingerprint') == fingerprint(entries, a['watch'])
            pending += not reviewed
            print(f"{'REVIEWED' if reviewed else 'REVIEW'} {a['id']}: {a['title']}")
            print('  Changed: ' + ', '.join(hits))
            print('  Used: ' + ', '.join(refs.get(a.get('path') or a.get('url'), ['not placed'])))
            print('  Recipe: ' + a['recipe'])
        print(f'{pending} asset review(s) pending. Planned/source-only items remain capture backlog.')
        return int(bool(pending))
    if args.command in {'approve', 'replace'}:
        asset = next((a for a in data['assets'] if a['id'] == args.id), None)
        if asset is None:
            raise ValueError(f'Unknown asset: {args.id}')
        if args.command == 'approve':
            if asset['status'] != 'published':
                raise ValueError('Only published assets can be approved')
            if not args.note.strip():
                raise ValueError('Review note must explain why the visual remains accurate')
            asset['review'] = {'head': git(root, 'rev-parse', args.head),
                               'fingerprint': fingerprint(tree(root, args.head), asset['watch']),
                               'decision': args.decision, 'note': args.note,
                               'date': datetime.date.today().isoformat()}
        else:
            if not asset.get('path'):
                raise ValueError('Replacement requires a cataloged local stable path')
            info = media_info(args.file)
            target = local_path(root, asset['path'])
            if target.suffix != args.file.suffix:
                raise ValueError('Keep the format for a stable-path swap; register a new variant for a format change')
            target.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as f:
                temporary = Path(f.name)
            try:
                shutil.copyfile(args.file, temporary)
                temporary.replace(target)
            finally:
                temporary.unlink(missing_ok=True)
            asset.update(info)
            asset['status'] = 'published'
            asset['capture'] = {'pluginVersion': args.plugin_version, 'platform': args.platform, 'date': args.date}
            asset.pop('review', None)
        (root / CATALOG).write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n')
    (root / INDEX).write_text(index_text(data, references(root)))
    print(f'Updated {INDEX}')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        print(f'Media error: {error}', file=sys.stderr)
        sys.exit(2)
